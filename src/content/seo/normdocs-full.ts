/**
 * Карта: нормализованный код → slug, для построения кросс-ссылок.
 * Нормализация: upper case, удалить лишние пробелы, точки, тире.
 */
export const normDocByCode: Record<string, string> = (() => {
  const map: Record<string, string> = {};
  for (const doc of normDocsFull) {
    map[normalizeCode(doc.code)] = doc.slug;
    // Также — альтернативные написания
    if (doc.code.startsWith("ГОСТ")) {
      // Без года
      const noYear = doc.code.replace(/-\d+.*$/, "");
      map[normalizeCode(noYear)] = doc.slug;
    }
  }
  // Ручные алиасы: отменённые/заменённые редакции → актуальная страница
  // (стратегия дедупликации: editions одного документа — алиасом на актуальную)
  map[normalizeCode("ГОСТ Р 52857.2-2007")] = "gost-34233.2-2017";
  map[normalizeCode("ГОСТ Р 52857.2")] = "gost-34233.2-2017";
  map[normalizeCode("ГОСТ 27.002-89")] = "gost-27.002-2015";
  map[normalizeCode("РД 03-380")] = "rd-03-380-00";
  map[normalizeCode("СНиП 2.02.01")] = "snip-2.02.01-83";
  map[normalizeCode("СНиП 2.02.01-83*")] = "snip-2.02.01-83";
  map[normalizeCode("ISO 4866")] = "iso-4866-2010";
  map[normalizeCode("ISO 4866:2010")] = "iso-4866-2010";
  map[normalizeCode("ГОСТ Р 22.0.05-97")] = "gost-r-22.0.05-2020";
  return map;
})();

export function normalizeCode(code: string): string {
  return code
    .toUpperCase()
    .replace(/\s+/g, " ")
    .replace(/[.\-]/g, "")
    .trim();
}

/**
 * Найти slug документа по коду из текста.
 * Возвращает slug или null.
 */
export function findDocByCode(code: string): string | null {
  return normDocByCode[normalizeCode(code)] ?? null;
}

